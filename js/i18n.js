window.i18n = {
  lang: document.body?.dataset?.lang || 'sq',

  t(key, vars = {}) {
    let str = translations[this.lang]?.[key] || translations.sq[key] || key;
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
    return str;
  },

  apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      let text = this.t(key);

      if (key === 'pointsEquiv') {
        text = this.t(key, { n: 2 });
      }
      if (key === 'nextReward') {
        text = this.t(key, { n: 1 });
      }

      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else {
        el.textContent = text;
      }
    });

    document.documentElement.lang = this.lang;
  },

  setLang(code) {
    this.lang = code;
    this.apply();
  },
};
